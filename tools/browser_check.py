from playwright.sync_api import sync_playwright
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
import http.server,threading,functools
server=http.server.ThreadingHTTPServer(('127.0.0.1',0),functools.partial(http.server.SimpleHTTPRequestHandler,directory=str(ROOT)))
threading.Thread(target=server.serve_forever,daemon=True).start()
with sync_playwright() as p:
 b=p.chromium.launch(executable_path=str(ROOT.parent/'mummy-godot-tools/chrome-headless-shell-linux64/chrome-headless-shell'),headless=True,args=['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
 page=b.new_page(viewport={'width':1100,'height':820},device_scale_factor=1)
 page.on('console',lambda m:print('CONSOLE',m.type,m.text[:300]))
 page.on('pageerror',lambda e:print('ERROR',e))
 page.goto(f'http://127.0.0.1:{server.server_port}/build/web/index.html')
 page.wait_for_timeout(7000)
 page.screenshot(path=str(ROOT/'review/home-desktop.png'))
 page.mouse.click(550,677)
 page.wait_for_timeout(400)
 page.screenshot(path=str(ROOT/'review/instructions-desktop.png'))
 page.mouse.click(550,489)
 page.wait_for_timeout(400)
 page.screenshot(path=str(ROOT/'review/quiz-desktop.png'))
 for i in range(5):
  page.mouse.click(350,340)
  page.wait_for_timeout(150)
  page.mouse.click(800,652)
  page.wait_for_timeout(250)
 page.screenshot(path=str(ROOT/'review/result-desktop.png'))
 page.mouse.click(375,310)
 page.wait_for_timeout(250)
 page.screenshot(path=str(ROOT/'review/modal-desktop.png'))
 page.mouse.click(20,400)
 page.wait_for_timeout(200)
 page.mouse.click(710,430)
 page.wait_for_timeout(200)
 page.screenshot(path=str(ROOT/'review/organs-modal-desktop.png'))
 page.keyboard.press('Escape')
 page.set_viewport_size({'width':390,'height':844})
 page.wait_for_timeout(500)
 page.screenshot(path=str(ROOT/'review/result-phone.png'))
 page.mouse.click(60,280)
 page.wait_for_timeout(250)
 page.screenshot(path=str(ROOT/'review/modal-phone.png'))
 page.keyboard.press('Escape')
 page.set_viewport_size({'width':768,'height':1024})
 page.wait_for_timeout(500)
 page.screenshot(path=str(ROOT/'review/result-tablet.png'))
 print('TITLE',page.title())
 b.close()
